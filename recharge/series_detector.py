_SERIES_CACHE = None


def _parse_rows(reader):
    table = {}
    for row in reader:
        raw_series = "".join(ch for ch in str(row.get("Series") or "") if ch.isdigit())
        raw_op = str(row.get("operator") or "").strip().upper()
        raw_circle = str(row.get("circle") or "").strip().upper()

        if len(raw_series) == 4 and raw_op in OPERATOR_MAP:
            table[raw_series] = {
                "series": raw_series,
                "operator_code": raw_op,
                "operator": OPERATOR_MAP[raw_op],
                "circle_code": raw_circle,
                "circle": CIRCLE_MAP.get(raw_circle, raw_circle or "India"),
            }
    return table


def load_series_table(csv_path: str = DEFAULT_CSV_PATH):
    global _SERIES_CACHE
    if _SERIES_CACHE is not None:
        return _SERIES_CACHE

    if csv_path and os.path.exists(csv_path):
        with open(csv_path, mode="r", encoding="utf-8", newline="") as f:
            table = _parse_rows(csv.DictReader(f))
    else:
        table = _parse_rows(csv.DictReader(io.StringIO(SERIES_DATA)))

    _SERIES_CACHE = table
    return table


def detect_operator_by_number(mobile_number: str, csv_path: str = DEFAULT_CSV_PATH):
    digits = "".join(ch for ch in str(mobile_number or "") if ch.isdigit())
    if len(digits) < 4:
        return {"found": False, "operator": "", "circle": "", "series": ""}

    prefix4 = digits[:4]
    table = load_series_table(csv_path)
    info = table.get(prefix4)

    if not info:
        return {"found": False, "operator": "", "circle": "", "series": prefix4}

    return {
        "found": True,
        "series": prefix4,
        "operator_code": info["operator_code"],
        "operator": info["operator"],
        "circle_code": info["circle_code"],
        "circle": info["circle"],
    }
